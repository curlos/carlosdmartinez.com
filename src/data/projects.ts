export type Project = {
  slug: string;
  name: string;
  /** Shown to the left of the name on cards and the project page. */
  icon: {
    image: StaticImageData;
    /** Adds a light outline, for dark icons that would disappear on the dark background. */
    outline?: boolean;
  };
  card: {
    image: StaticImageData;
    alt: string;
    /** object-position of the 16:10 crop. Defaults to "top left". */
    position?: string;
    /** Shown behind the image while it loads. Defaults to surface-2. */
    background?: string;
    description: string;
    badge: string;
    stack: string[];
  };
  liveUrl?: string;
  codeUrl: string;
  page: ProjectPage;
};

export type Feature = {
  title: string;
  description: string;
  page: string;
  image?: StaticImageData;
  alt?: string;
  /** "contain" shows the whole image on a padded dark background (tall popups, wide strips). */
  fit?: "contain";
  /** object-position of the 16:10 crop. Defaults to "top left". */
  position?: string;
  /** Not rendered: notes which screenshot is still needed. The feature stays hidden until `image` is set. */
  placeholder?: string;
};

export type DiagramNode = {
  id: string;
  title: string;
  sub: string;
  /** Top-left corner in the 1056-wide desktop viewBox; every box is 260×84. */
  x: number;
  y: number;
  hub: boolean;
};

export type DiagramEdge = {
  from: string;
  to: string;
  label: string;
  /** Desktop geometry: line endpoints (drawn from `from` to `to`) and label position. */
  line: [number, number, number, number];
  labelAt: [number, number];
  anchor: "start" | "middle" | "end";
  /** One arrow, from the side that makes the request to the side that answers. Set for real two-way traffic (pushes, subscriptions). */
  twoWay?: boolean;
};

